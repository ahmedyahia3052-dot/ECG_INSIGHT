function ref(organization: string, title: string, year?: number, url?: string): MicReference {
  return { organization, title, year, url };
}

function dx(
  partial: Omit<MicDiagnosisEntry, "references"> & { references?: MicReference[] },
): MicDiagnosisEntry {
  return {
    references: partial.references ?? [
      ref("ACC/AHA", "Guidelines for ECG interpretation in clinical practice", 2022),
    ],
    ...partial,
  };
}

